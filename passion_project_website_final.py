# Utility functions
def money(x):
    return f"${x:,.0f}"

def pct(x):
    return f"{x:.2f}%"

def calculate_metrics(
    purchase_price,
    down_payment,
    monthly_rent,
    annual_property_tax,
    annual_insurance,
    annual_maintenance,
    annual_management,
    vacancy_rate,
    closing_costs,
    renovation_costs
):
    # Total initial investment
    loan_amount = max(purchase_price - down_payment, 0)

    total_initial_investment = (
        down_payment + closing_costs + renovation_costs
    )

    # Income
    gross_annual_rent = monthly_rent * 12
    vacancy_loss = gross_annual_rent * (vacancy_rate / 100)
    effective_gross_income = gross_annual_rent - vacancy_loss

    # Operating expenses
    total_operating_expenses = (
        annual_property_tax
        + annual_insurance
        + annual_maintenance
        + annual_management
    )

    annual_noi = effective_gross_income - total_operating_expenses

    # Simple cap rate
    cap_rate = (
        annual_noi / purchase_price * 100
        if purchase_price > 0 else 0
    )

    # Approximate mortgage payment using 30-year fixed loan
    annual_interest_rate = 0.065
    monthly_rate = annual_interest_rate / 12
    number_payments = 30 * 12

    if loan_amount > 0:
        monthly_mortgage = (
            loan_amount
            * (monthly_rate * (1 + monthly_rate) ** number_payments)
            / ((1 + monthly_rate) ** number_payments - 1)
        )
    else:
        monthly_mortgage = 0

    annual_debt_service = monthly_mortgage * 12

    annual_cash_flow = annual_noi - annual_debt_service

    cash_on_cash_roi = (
        annual_cash_flow / total_initial_investment * 100
        if total_initial_investment > 0 else 0
    )

    property_roi = (
        annual_cash_flow / purchase_price * 100
        if purchase_price > 0 else 0
    )

    monthly_cash_flow = annual_cash_flow / 12

    rent_to_price = (
        monthly_rent / purchase_price * 100
        if purchase_price > 0 else 0
    )

    annual_rent_yield = (
        gross_annual_rent / purchase_price * 100
        if purchase_price > 0 else 0
    )

    return {
        "loan_amount": loan_amount,
        "initial_investment": total_initial_investment,
        "gross_rent": gross_annual_rent,
        "vacancy_loss": vacancy_loss,
        "effective_income": effective_gross_income,
        "operating_expenses": total_operating_expenses,
        "noi": annual_noi,
        "monthly_mortgage": monthly_mortgage,
        "annual_debt_service": annual_debt_service,
        "annual_cash_flow": annual_cash_flow,
        "monthly_cash_flow": monthly_cash_flow,
        "cap_rate": cap_rate,
        "cash_on_cash_roi": cash_on_cash_roi,
        "property_roi": property_roi,
        "rent_to_price": rent_to_price,
        "annual_rent_yield": annual_rent_yield
    }

def load_market_data(file):
    if file is None:
        return DEMO_DATA.copy(), "Demo market dataset"

    try:
        df = pd.read_csv(file.name)

        # Normal column names
        rename_map = {}
        for c in df.columns:
            cl = c.strip().lower().replace(" ", "_")
            if cl in ["year", "date_year"]:
                rename_map[c] = "Year"
            elif cl in ["median_price", "median_home_price", "home_price", "price"]:
                rename_map[c] = "Median_Price"
            elif cl in ["median_rent", "rent", "median_monthly_rent"]:
                rename_map[c] = "Median_Rent"

        df = df.rename(columns=rename_map)

        required = {"Year", "Median_Price", "Median_Rent"}
        if not required.issubset(df.columns):
            return DEMO_DATA.copy(), (
                "Uploaded CSV is missing required columns. "
                "Using demo data instead."
            )

        df = df[["Year", "Median_Price", "Median_Rent"]].copy()
        df["Year"] = pd.to_numeric(df["Year"], errors="coerce")
        df["Median_Price"] = pd.to_numeric(df["Median_Price"], errors="coerce")
        df["Median_Rent"] = pd.to_numeric(df["Median_Rent"], errors="coerce")
        df = df.dropna().sort_values("Year")

        if len(df) < 5:
            return DEMO_DATA.copy(), (
                "Need at least 5 historical rows. Using demo data instead."
            )

        return df, "Uploaded local market dataset"

    except Exception as e:
        return DEMO_DATA.copy(), f"Could not read CSV: {e}. Using demo data."

def appreciation_prediction(df, forecast_years):
    X = df[["Year"]].values
    y = df["Median_Price"].values

    # Random Forest for nonlinear relationships
    model = RandomForestRegressor(
        n_estimators=300,
        random_state=42,
        min_samples_leaf=1
    )
    model.fit(X, y)

    last_year = int(df["Year"].max())
    future_years = np.arange(
        last_year + 1,
        last_year + forecast_years + 1
    )

    predictions = model.predict(future_years.reshape(-1, 1))

    # Historical CAGR
    first_price = float(df.iloc[0]["Median_Price"])
    last_price = float(df.iloc[-1]["Median_Price"])
    year_span = max(int(df.iloc[-1]["Year"] - df.iloc[0]["Year"]), 1)

    cagr = (
        ((last_price / first_price) ** (1 / year_span) - 1) * 100
        if first_price > 0 else 0
    )

    return future_years, predictions, cagr

def market_insights(df):
    first = df.iloc[0]
    last = df.iloc[-1]

    years = max(int(last["Year"] - first["Year"]), 1)

    price_growth = (
        (last["Median_Price"] / first["Median_Price"] - 1) * 100
        if first["Median_Price"] > 0 else 0
    )

    rent_growth = (
        (last["Median_Rent"] / first["Median_Rent"] - 1) * 100
        if first["Median_Rent"] > 0 else 0
    )

    latest_price = last["Median_Price"]
    latest_rent = last["Median_Rent"]

    price_cagr = (
        ((last["Median_Price"] / first["Median_Price"]) ** (1 / years) - 1) * 100
        if first["Median_Price"] > 0 else 0
    )

    rent_cagr = (
        ((last["Median_Rent"] / first["Median_Rent"]) ** (1 / years) - 1) * 100
        if first["Median_Rent"] > 0 else 0
    )

    price_to_annual_rent = (
        latest_price / (latest_rent * 12)
        if latest_rent > 0 else 0
    )

    return {
        "price_growth": price_growth,
        "rent_growth": rent_growth,
        "price_cagr": price_cagr,
        "rent_cagr": rent_cagr,
        "latest_price": latest_price,
        "latest_rent": latest_rent,
        "price_to_annual_rent": price_to_annual_rent
    }

def recommendation(metrics, market, predicted_growth):
    score = 0
    reasons = []

    # Cash flow
    if metrics["monthly_cash_flow"] > 500:
        score += 2
        reasons.append("Strong projected monthly cash flow.")
    elif metrics["monthly_cash_flow"] > 0:
        score += 1
        reasons.append("Positive projected monthly cash flow.")
    else:
        score -= 2
        reasons.append("Projected monthly cash flow is negative.")

    # Cap rate
    if metrics["cap_rate"] >= 7:
        score += 2
        reasons.append("Cap rate is relatively strong.")
    elif metrics["cap_rate"] >= 5:
        score += 1
        reasons.append("Cap rate is moderate.")

    # Cash-on-cash return
    if metrics["cash_on_cash_roi"] >= 10:
        score += 2
        reasons.append("Cash-on-cash return is attractive.")
    elif metrics["cash_on_cash_roi"] >= 5:
        score += 1
        reasons.append("Cash-on-cash return is moderate.")

    # Market
    if market["price_cagr"] >= 4:
        score += 1
        reasons.append("Historical home-price growth is positive.")
    elif market["price_cagr"] < 0:
        score -= 1
        reasons.append("Historical home-price growth has been negative.")

    # Forecast
    if predicted_growth >= 4:
        score += 1
        reasons.append("Model forecast indicates positive appreciation.")
    elif predicted_growth < 0:
        score -= 1
        reasons.append("Model forecast indicates declining prices.")

    if score >= 6:
        rating = "STRONG OPPORTUNITY"
    elif score >= 3:
        rating = "POTENTIAL OPPORTUNITY"
    elif score >= 0:
        rating = "NEEDS MORE ANALYSIS"
    else:
        rating = "HIGHER RISK"

    return rating, reasons

